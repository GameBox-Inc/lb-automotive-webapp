#!/bin/bash
# Jenkins Deployment Script for LB Automotive Dashboard
# This script is executed on the production server by Jenkins

set -e

# Parse arguments
DEPLOY_DIR="$1"
BRANCH_NAME="$2"
SECRET_KEY="$3"
ALLOWED_ORIGINS="$4"
LLM_PROVIDER="$5"
ANTHROPIC_API_KEY="$6"
TWILIO_ACCOUNT_SID="$7"
TWILIO_AUTH_TOKEN="$8"
TWILIO_PHONE_NUMBER="$9"

echo "========================================"
echo "🚀 LB Automotive Deployment Script"
echo "========================================"
echo "Deploy Dir: $DEPLOY_DIR"
echo "Branch: $BRANCH_NAME"
echo "Time: $(date)"
echo "========================================"

# Verify deployment directory exists
if [ ! -d "$DEPLOY_DIR" ]; then
    echo "❌ Error: Directory $DEPLOY_DIR does not exist"
    exit 1
fi

cd "$DEPLOY_DIR"

# Verify git repository
if [ ! -d ".git" ]; then
    echo "❌ Error: Not a git repository"
    exit 1
fi

# Create .env file for deployment
echo "📝 Creating .env file..."

cat > deployment/docker/.env << EOF
# LB Automotive Dashboard - Production Environment
# Auto-generated by Jenkins on $(date)

# Required Variables
SECRET_KEY=$SECRET_KEY
ALLOWED_ORIGINS=$ALLOWED_ORIGINS

# LLM Configuration
LLM_PROVIDER=${LLM_PROVIDER:-ollama}
OLLAMA_HOST=http://ollama:11434
OLLAMA_MODEL=smollm2:135m

# Database
DATABASE_URL=sqlite:////app/data/lb_automotive.db

# Redis
REDIS_URL=redis://redis:6379/0

# Security
CSP_POLICY=strict
EOF

# Add Anthropic config if provided
if [ -n "$ANTHROPIC_API_KEY" ]; then
    cat >> deployment/docker/.env << EOF

# Anthropic Configuration
ANTHROPIC_API_KEY=$ANTHROPIC_API_KEY
ANTHROPIC_MODEL=${ANTHROPIC_MODEL:-claude-3-5-sonnet-20241022}
EOF
fi

# Add Twilio config if provided
if [ -n "$TWILIO_ACCOUNT_SID" ]; then
    cat >> deployment/docker/.env << EOF

# Twilio Configuration
TWILIO_ACCOUNT_SID=$TWILIO_ACCOUNT_SID
TWILIO_AUTH_TOKEN=$TWILIO_AUTH_TOKEN
TWILIO_PHONE_NUMBER=$TWILIO_PHONE_NUMBER
EOF
fi

# Set secure permissions
chmod 600 deployment/docker/.env
echo "✅ .env file created"

# Pull latest code
echo "📥 Pulling latest code..."
CLEAN_BRANCH=$(echo "$BRANCH_NAME" | sed 's|origin/||')
echo "Cleaned branch: $CLEAN_BRANCH"
git fetch origin
git reset --hard origin/$CLEAN_BRANCH

# Stop existing containers
echo "🛑 Stopping existing containers..."
docker compose -f deployment/docker/docker-compose.yml down || true

# Pull latest images (if using registry)
echo "📦 Pulling Docker images..."
docker compose -f deployment/docker/docker-compose.yml pull || echo "⚠️ Could not pull images, will build locally"

# Build and start containers
echo "🔨 Building and starting containers..."
docker compose -f deployment/docker/docker-compose.yml up -d --build --force-recreate

# Wait for backend to be ready
echo "⏳ Waiting for backend to start..."
sleep 10

# Run database migrations
echo "🗄️ Running database migrations..."
docker exec lb-auto-backend python migrate_business_hours.py || echo "⚠️ Business hours migration may have already run"
docker exec lb-auto-backend python migrate_24_7_settings.py || echo "⚠️ 24/7 settings migration may have already run"

# Restart containers after migration
echo "🔄 Restarting containers..."
docker compose -f deployment/docker/docker-compose.yml restart

# Wait for services to stabilize
echo "⏳ Waiting for services to stabilize..."
sleep 10

# Show container status
echo "========================================"
echo "📊 Container Status"
echo "========================================"
docker compose -f deployment/docker/docker-compose.yml ps

echo "========================================"
echo "✅ Deployment Complete!"
echo "========================================"
echo "Backend URL: http://178.156.223.196:8000"
echo "Frontend URL: http://178.156.223.196"
echo "========================================"

# Check backend logs for any immediate errors
echo "📋 Recent backend logs:"
docker logs lb-auto-backend --tail 20

exit 0
